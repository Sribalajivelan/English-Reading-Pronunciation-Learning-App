/** Explanation for a letter's example word. Falls back to a general note built from the letter data. */
export function explainFor(L, word, wordTa, letterTa, isVowel) {
  const known = EXPLAIN[L + ':' + word]
  if (known) return known
  return {
    sound: L + ' = ' + letterTa,
    why: isVowel
      ? `${word} என்ற சொல்லில் ${L} இப்படி ஒலிக்கும்: "${wordTa}". தமிழ் எழுத்தில் ஆங்கில ஒலிகள் முழுமையாக அமையாது; இது அருகிலுள்ள ஒலி மட்டுமே. சரியான ஒலிக்கு ஒலிப்பொத்தானைக் கேளுங்கள்.`
      : `${word} என்ற சொல்லில் ${L} ஒலி "${letterTa}" என வரும்: "${wordTa}". தமிழ் எழுத்து ஆங்கில ஒலியை அருகில் மட்டுமே காட்டும்; சரியான ஒலிக்கு ஒலிப்பொத்தானைக் கேளுங்கள்.`,
    tip: '',
    compare: [[word, wordTa]],
  }
}
